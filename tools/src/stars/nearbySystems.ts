/**
 * The nearest star systems, by the names people know them by.
 *
 * Most of the Sun's neighbours have no IAU proper name: they are known by the catalogue
 * that first measured them -- Wolf 359 (Max Wolf's proper-motion survey), Lalande 21185,
 * Ross 128, Luyten's Star, Groombridge 34 -- and none of the catalogues read here carries
 * those names. So they are listed here, for every star within 7.5 pc in the catalogue
 * this app builds, 138 stars in roughly 115 systems: the hundred nearest systems the
 * catalogue holds and some margin, so the hundredth does not depend on the last decimal
 * of a parallax.
 *
 * **How the list was made, 2026-10-22.** The stars within 7.5 pc were taken from this
 * build's own output and their identifiers looked up in SIMBAD (CDS, Wenger et al. 2000,
 * A&AS 143, 9), joined by Gaia DR3 source_id or, for the stars Gaia saturates, by HIP.
 * From SIMBAD come the spectral types and the designations below (GJ numbers, variable-
 * star names, Bayer letters, the names SIMBAD files as NAME). The display names are the
 * customary ones, as the RECONS census of the nearest stars (Henry et al. 2018, AJ 155,
 * 265) and the literature use them; where a star has an IAU name too, the IAU's is
 * displayed and this one becomes a designation (names3d.ts).
 *
 * **Systems** are as SIMBAD and the Gliese-Jahreiss catalogue give them: components
 * sharing a GJ number (GJ 559 A and B), or a wider companion recognised as one (Proxima,
 * GJ 551, of Alpha Centauri). A system named here but with one star in the catalogue --
 * Procyon, whose white dwarf Gaia does not measure, or Gliese 229, whose brown dwarf it
 * cannot -- is still a system, and says so.
 *
 * Three entries are a Hipparcos pair held as one star at its photocentre (70 Ophiuchi,
 * 36 Ophiuchi, Xi Bootis): Gaia resolves them, and their components are drawn once, as
 * the sky entry (see STAR3D_COMPONENT_RADIUS_ARCSEC).
 *
 * What is missing is missing from Gaia: the nearest brown dwarfs (Luhman 16, WISE
 * 0855-0714) and the white dwarfs beside bright stars (Procyon B) have no five-parameter
 * solution in DR3, so they are not in the catalogue and not named here. The ranks in the
 * index are among the systems the catalogue holds -- said so, rather than numbered as
 * RECONS numbers them.
 *
 * A star here that the build cannot find is reported in the log (NEARBY NOT FOUND): an
 * id that went stale, to be fixed here, not ignored.
 */

export interface NearbyStar {
  /** The common name: "Proxima Centauri", "Wolf 359", "61 Cygni A". */
  readonly name: string;
  /** The system it belongs to where it is multiple ("Alpha Centauri"); null if single. */
  readonly system: string | null;
  /** Gaia DR3 source_id, the join to the catalogue; null for a star Gaia saturates. */
  readonly gaiaDr3: string | null;
  readonly hip: number | null;
  /** SIMBAD's spectral type; the Hipparcos one wins where the star has it. */
  readonly spectralType: string | null;
  /** Other names to search by: "GJ 406", "CN Leo". */
  readonly designations?: readonly string[];
}

