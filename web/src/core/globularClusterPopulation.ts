/**
 * The stellar populations the globular clusters are sampled from (globularClusters.ts): how
 * many of a cluster's living stars there are at each visual absolute magnitude, and their
 * colour, at four metallicities.
 *
 * **A model**, as the nuclear cluster's population is (nuclearClusterPopulation.ts), and made
 * the same way: PARSEC v1.2S isochrones (Bressan et al. 2012, MNRAS 427, 127) with COLIBRI
 * S_37, from the CMD 3.9 service (https://stev.oapd.inaf.it/cgi-bin/cmd), in UBVRIJHK with YBC
 * bolometric corrections (YBCnewVega) and no extinction, Reimers mass loss eta = 0.2 on the
 * red giant branch, populated with the Kroupa (2001) canonical IMF corrected for unresolved
 * binaries -- one age, 12 Gyr (log t = 10.0792), the age the Milky Way's globular clusters
 * are measured near (VandenBerg et al. 2013, ApJ 775, 134: 11 to 13 Gyr for most), and
 * [M/H] = -2.0, -1.5, -1.0 and -0.5. Queried 2026-11-03; reduced by
 * tools/src/stars/reduceIsochrones.ts (each isochrone alone, share 1), its dwarfs and
 * evolved stars then merged bin by bin.
 *
 * A cluster takes the table nearest its [M/H], from Harris's [Fe/H] plus 0.21: the alpha
 * elements globular cluster stars are rich in, [alpha/Fe] = +0.3, count as metals in the
 * isochrones' [M/H] (Salaris, Chieffi & Straniero 1993, ApJ 414, 580: [M/H] = [Fe/H] +
 * log10(0.638 f + 0.362), f = 10^[alpha/Fe]). One without a metallicity takes -1.5.
 *
 * What it does not have: the spread of ages and of helium some clusters show (Omega Cen's
 * several populations), the blue horizontal branches a single Reimers eta does not make,
 * blue stragglers, remnants -- dark -- and binaries, folded into single stars by the IMF.
 */

