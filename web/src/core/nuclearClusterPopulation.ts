/**
 * The stellar population the nuclear star cluster is sampled from (nuclearCluster.ts): how
 * many of its living stars there are at each visual absolute magnitude, and their colours.
 *
 * **A model.** No survey counts the cluster's stars to the bottom of the main sequence --
 * at 8 kpc and behind 2.4 to 2.6 magnitudes of extinction even in K, it is counted down to
 * K = 18 or 19, stars of about the Sun's mass. Below that, and in visible light at all,
 * it has to be modelled, and this is that model:
 *
 * - **its ages**: the star-formation history Schödel et al. 2020 (A&A 641, A102; arXiv
 *   2007.15950) fit to the cluster's K luminosity function, their "Mixed" column -- 72% of
 *   the mass formed 11 Gyr ago, 15% at 7 Gyr, 9% at 3 Gyr, 2% at 2 Gyr. The last 2%, younger
 *   than a gigayear, is left out; the young stars of the central parsec are drawn as
 *   measured instead (galacticCentreStars.ts);
 * - **its metallicity**: [M/H] = +0.2, their "slightly super-solar";
 * - **its stars**: PARSEC v1.2S isochrones at those four ages (Bressan et al. 2012, MNRAS
 *   427, 127), from the CMD 3.9 service (https://stev.oapd.inaf.it/cgi-bin/cmd), in UBVRIJHK
 *   with YBC bolometric corrections and no extinction, populated with the Kroupa (2001)
 *   canonical IMF corrected for unresolved binaries, as CMD does it.
 *
 * Reduced by tools/src/stars/reduceIsochrones.ts, whose header gives the query, to: per
 * 0.1 magnitude of M_V, the share of all the living stars there -- dwarfs (pre-main
 * sequence and main sequence) and evolved stars apart -- and their mean B-V and V-K; and
 * the evolved stars again per 0.1 magnitude of M_K. Not
 * computed in the browser and not fetched in CI: the table is read once, as a table in a
 * paper is.
 *
 * **Checked against what is measured** (nuclearCluster.test.ts): its K luminosity function
 * rises 0.28 dex a magnitude between M_K = -6.2 and -3.2 (EVOLVED_BY_K), where the
 * cluster's measured one rises 0.27 +- 0.02 (Schödel et al. 2010, A&A 511, A18, for Ks 11
 * to 14, M_K -6.1 to -3.1 at their extinction and this distance) and 0.26 +- 0.02
 * (Gallego-Cano et al. 2018); and its red clump peaks between M_K = -1.6 and -1.5, where
 * the cluster's own clump falls: Ks = 15.59 +- 0.04 behind A_Ks = 2.54 (Schödel et al.
 * 2010) is M_K = -1.54 at GRAVITY's distance.
 *
 * What the model does not have: remnants (white dwarfs, neutron stars, black holes), which
 * are dark; binaries, which the IMF's correction folds into single stars; and a spread of
 * metallicity.
 */

